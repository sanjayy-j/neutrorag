"""The CONFLICTS experiments (memo Step 9): 3a r-ablation, 3b disagree by type,
3c the policy test, 3d Gate A repeated.

Replays the per-passage NLI outputs cached by score_conflicts.py, so every
condition below sees bit-identical model output and nothing but the named
variable changes. Run that first.

    python experiments/score_conflicts.py
    python experiments/run_conflicts_eval.py

3c is the experiment that has never been run. Every result to date has graded
the SCORER's label attribution; the project's actual claim is about choosing
ACTIONS, and CONFLICTS annotates an expected behaviour per conflict type. Only
two of the five types map onto a NeutroRAG action, and "Conflict due to
misinformation" (5 instances) is excluded from every per-type claim as too small
to support one.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "experiments"))

from make_results_table import (  # noqa: E402
    CHANNELS, accuracy, confusion, confusion_md, mcnemar_exact, per_class, wald_ci,
)
from neutrorag.conflicts import TOO_FEW_TO_EVALUATE, TYPE_TO_EXPECTED_ACTION  # noqa: E402
from neutrorag.core import clamp  # noqa: E402
from neutrorag.policy import Action, NeutroPolicy  # noqa: E402
from neutrorag.scoring import Evidence, NLIRetrievalScorer  # noqa: E402

ACTIONS = [a.value for a in Action]


class _ReplayPerPassage:
    """Replays the cached (e, n, c) for each passage, in order."""

    def __init__(self, triples):
        self._t = list(triples)
        self._i = 0

    def predict(self, premise, hypothesis):
        out = self._t[self._i]
        self._i += 1
        return out


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cache", default="data/conflicts_scored.jsonl")
    p.add_argument("--outdir", default="results")
    p.add_argument("--r-const", type=float, default=0.9)
    return p.parse_args()


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                       cwd=REPO, text=True).strip()
    except Exception:  # pragma: no cover
        return "unknown"


def load_cache(path: Path):
    header, rows = None, []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            rec = json.loads(line)
            if rec.get("_header"):
                header = rec
            else:
                rows.append(rec)
    return header, rows


def build(rec):
    ev = [Evidence(p["text"], p["relevance"], source=p["source"]) for p in rec["passages"]]
    triples = [(p["e"], p["n"], p["c"]) for p in rec["passages"]]
    return ev, triples


def score(rec, r_override=None):
    ev, triples = build(rec)
    kw = {"nli": _ReplayPerPassage(triples)}
    if r_override is not None:
        kw["r_override"] = r_override
    s = NLIRetrievalScorer(**kw)
    return s, s.score(rec["question"], ev), ev


def prf_table(pairs, labels):
    """precision/recall/F1 per label from (gold, pred) pairs."""
    out = {}
    for lab in labels:
        tp = sum(1 for g, p in pairs if g == lab and p == lab)
        fp = sum(1 for g, p in pairs if g != lab and p == lab)
        fn = sum(1 for g, p in pairs if g == lab and p != lab)
        prec = tp / (tp + fp) if tp + fp else 0.0
        rec = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
        out[lab] = (prec, rec, f1, tp + fn)
    return out


def main() -> None:
    args = parse_args()
    cache = REPO / args.cache
    if not cache.exists():
        print(f"missing {cache}. Run: python experiments/score_conflicts.py")
        raise SystemExit(1)
    header, rows = load_cache(cache)
    commit = git_commit()
    L = []

    def emit(s=""):
        print(s)
        L.append(s)

    emit("# CONFLICTS experiments (memo Step 9)")
    emit()
    emit(f"Cache: `{args.cache}` | model `{header['model']}` | sampling "
         f"`{json.dumps(header['sampling'])}`")
    emit(f"Generated by `python experiments/run_conflicts_eval.py` | commit `{commit}`")
    emit()
    emit(f"N = {len(rows)} instances, "
         f"{sum(len(r['passages']) for r in rows)} passages.")
    emit()
    emit("Per-type counts in this run:")
    emit()
    emit("| conflict type | n |")
    emit("|---|---:|")
    for t, k in Counter(r["conflict_type"] for r in rows).most_common():
        emit(f"| {t} | {k} |")
    emit()

    # ---------------- r: does it vary here? --------------------------------
    emit("## Does r vary on CONFLICTS?")
    emit()
    comps = defaultdict(list)
    r_vals = []
    for rec in rows:
        s, _, ev = score(rec)
        b = s.sufficiency(rec["question"], ev)
        r_vals.append(b.r)
        for k, v in b.components.items():
            comps[k].append(v)
    rs = sorted(r_vals)
    emit(f"- r: min {rs[0]:.3f}, median {rs[len(rs)//2]:.3f}, max {rs[-1]:.3f}, "
         f"{len(set(round(v,6) for v in r_vals))} distinct values")
    emit(f"- instances with r <= 0.5 (the F12 regime): "
         f"**{sum(1 for v in r_vals if v <= 0.5)}/{len(r_vals)}** "
         f"(FEVER was 143/200)")
    emit()
    emit("| component | min | median | max | constant? |")
    emit("|---|---:|---:|---:|---|")
    for k, v in comps.items():
        sv = sorted(v)
        const = "**SATURATED**" if len(set(round(x, 6) for x in v)) == 1 else "varies"
        emit(f"| {k} | {sv[0]:.3f} | {sv[len(sv)//2]:.3f} | {sv[-1]:.3f} | {const} |")
    emit()

    # ---------------- 3b: disagree by conflict type ------------------------
    emit("## 3b. `disagree` by annotated conflict type")
    emit()
    dis_by_type = defaultdict(list)
    for rec in rows:
        tr = [(p["e"], p["n"], p["c"]) for p in rec["passages"]]
        raw = 2.0 * max(min(a[0], b[2]) for a in tr for b in tr) if tr else 0.0
        d = clamp(raw)
        d_pooled_e = sum(p["relevance"] * p["e"] for p in rec["passages"])
        d_pooled_c = sum(p["relevance"] * p["c"] for p in rec["passages"])
        w = sum(p["relevance"] for p in rec["passages"]) or 1.0
        d_old = clamp(2.0 * min(d_pooled_e / w, d_pooled_c / w))
        dis_by_type[rec["conflict_type"]].append((d, d_old, raw))
    emit("| conflict type | n | median pairwise | frac > 0.1 | frac AT CLAMP (=1.0) | "
         "median raw (unclamped) | median POOLED (old) |")
    emit("|---|---:|---:|---:|---:|---:|---:|")
    for t, vals in sorted(dis_by_type.items(), key=lambda kv: -len(kv[1])):
        new = sorted(v[0] for v in vals); old = sorted(v[1] for v in vals)
        raws = sorted(v[2] for v in vals)
        at_clamp = sum(1 for x in new if x >= 1.0 - 1e-9) / len(new)
        emit(f"| {t} | {len(vals)} | {new[len(new)//2]:.3f} | "
             f"{sum(1 for x in new if x > 0.1)/len(new):.1%} | {at_clamp:.1%} | "
             f"{raws[len(raws)//2]:.3f} | {old[len(old)//2]:.3f} |")
    emit()
    emit("FEVER reference (pooled): median 0.011, 4.5% of rows above 0.1.")
    emit()
    # compare on the RAW (unclamped) statistic: if most values sit at the clamp,
    # the clamped comparison would be uninformative by construction.
    a = [v[2] for v in dis_by_type.get("Conflicting opinions and research outcomes", [])]
    b = [v[2] for v in dis_by_type.get("No conflict", [])]
    if a and b:
        sa, sb = sorted(a), sorted(b)
        ma, mb = sa[len(sa)//2], sb[len(sb)//2]
        # Mann-Whitney U, normal approximation (no scipy dependency)
        comb = sorted([(x, 0) for x in a] + [(x, 1) for x in b])
        ranks = {}
        i = 0
        while i < len(comb):
            j = i
            while j + 1 < len(comb) and comb[j + 1][0] == comb[i][0]:
                j += 1
            rr = (i + j) / 2 + 1
            for k in range(i, j + 1):
                ranks[k] = rr
            i = j + 1
        ra = sum(ranks[k] for k, (_, g) in enumerate(comb) if g == 0)
        na, nb = len(a), len(b)
        u = ra - na * (na + 1) / 2
        mu = na * nb / 2
        sd = math.sqrt(na * nb * (na + nb + 1) / 12)
        z = (u - mu) / sd if sd else 0.0
        p = math.erfc(abs(z) / math.sqrt(2))
        emit(f"**Conflicting opinions (median raw {ma:.3f}) vs No conflict (median raw {mb:.3f})**: "
             f"Mann-Whitney U = {u:.0f}, z = {z:.2f}, two-sided p = {p:.2e}. "
             f"Difference of medians = {ma - mb:+.3f}.")
        emit()
        emit(f"**Verdict: disagree {'DOES' if ma > mb and p < 0.05 else 'does NOT'} "
             f"separate the two types.**")
        emit()

    # ---------------- 3a / 3d: r-ablation and Gate A -----------------------
    emit("## 3a / 3d. r-ablation and Gate A, on data where r and disagree are live")
    emit()
    emit("There is no gold T/I/F channel in CONFLICTS, so attribution accuracy is not "
         "defined here. The comparison is therefore against the ACTION ground truth "
         "(3c), and the channel-level check below reports how often each system's "
         "argmax changes -- not an accuracy.")
    emit()
    dom_const, dom_suff, dom_raw = [], [], []
    for rec in rows:
        _, tif_c, _ = score(rec, r_override=args.r_const)
        _, tif_s, _ = score(rec)
        tr = [(p["e"], p["n"], p["c"]) for p in rec["passages"]]
        w = sum(p["relevance"] for p in rec["passages"]) or 1.0
        e = sum(p["relevance"] * p["e"] for p in rec["passages"]) / w
        n = sum(p["relevance"] * p["n"] for p in rec["passages"]) / w
        c = sum(p["relevance"] * p["c"] for p in rec["passages"]) / w
        dom_const.append(tif_c.dominant); dom_suff.append(tif_s.dominant)
        dom_raw.append(max({"T": e, "I": n, "F": c}, key={"T": e, "I": n, "F": c}.get))
    emit("| system | T | I | F |")
    emit("|---|---:|---:|---:|")
    for nm, d in (("(a) r = %.1f constant" % args.r_const, dom_const),
                  ("(b) r = sufficiency", dom_suff),
                  ("raw argmax(e,n,c)", dom_raw)):
        cnt = Counter(d)
        emit(f"| {nm} | {cnt.get('T',0)} | {cnt.get('I',0)} | {cnt.get('F',0)} |")
    agree = sum(1 for x, y in zip(dom_const, dom_suff) if x == y)
    emit()
    emit(f"(a) and (b) agree on {agree}/{len(rows)} instances; "
         f"(b) and raw agree on "
         f"{sum(1 for x,y in zip(dom_suff,dom_raw) if x==y)}/{len(rows)}.")
    emit()

    # ---------------- 3c: THE POLICY TEST ----------------------------------
    emit("## 3c. The policy test -- actions against external ground truth")
    emit()
    emit("Restricted to the two types that map to an action. "
         f"Excluded as too few to support a claim: {sorted(TOO_FEW_TO_EVALUATE)}. "
         "Complementary information and Outdated information are excluded because "
         "the five-way action space encodes no expected behaviour for them.")
    emit()
    policy = NeutroPolicy()
    pairs_suff, pairs_const = [], []
    action_by_type = defaultdict(Counter)
    for rec in rows:
        _, tif_s, _ = score(rec)
        _, tif_c, _ = score(rec, r_override=args.r_const)
        act_s = policy.decide_once(tif_s)[0].value
        act_c = policy.decide_once(tif_c)[0].value
        action_by_type[rec["conflict_type"]][act_s] += 1
        exp = TYPE_TO_EXPECTED_ACTION.get(rec["conflict_type"])
        if exp:
            pairs_suff.append((exp, act_s))
            pairs_const.append((exp, act_c))

    emit("Action distribution by conflict type (r = sufficiency, decide_once):")
    emit()
    emit("| conflict type | " + " | ".join(ACTIONS) + " |")
    emit("|---" * (len(ACTIONS) + 1) + "|")
    for t, cnt in sorted(action_by_type.items(), key=lambda kv: -sum(kv[1].values())):
        emit(f"| {t} | " + " | ".join(str(cnt.get(a, 0)) for a in ACTIONS) + " |")
    emit()

    labels = ["surface_contradiction", "answer"]
    for nm, pairs in (("r = sufficiency", pairs_suff),
                      ("r = %.1f constant" % args.r_const, pairs_const)):
        if not pairs:
            continue
        tbl = prf_table(pairs, labels)
        acc = sum(1 for g, p in pairs if g == p) / len(pairs)
        se, lo, hi = wald_ci(acc, len(pairs))
        emit(f"**{nm}** -- exact-match accuracy {acc:.3f} "
             f"(95% CI [{lo:.3f}, {hi:.3f}], n={len(pairs)})")
        emit()
        emit("| expected action | precision | recall | F1 | support |")
        emit("|---|---:|---:|---:|---:|")
        for lab in labels:
            pr, re_, f1, sup = tbl[lab]
            emit(f"| {lab} | {pr:.3f} | {re_:.3f} | {f1:.3f} | {sup} |")
        emit()

    outdir = REPO / args.outdir
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "conflicts_eval.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    with open(outdir / "conflicts_disagree.csv", "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["conflict_type", "disagree_pairwise", "disagree_pooled_old",
                    "disagree_pairwise_raw"])
        for t, vals in dis_by_type.items():
            for new, old, raw in vals:
                w.writerow([t, f"{new:.4f}", f"{old:.4f}", f"{raw:.4f}"])
    print(f"\nwrote {outdir/'conflicts_eval.md'} and {outdir/'conflicts_disagree.csv'}")


if __name__ == "__main__":
    main()
