"""The r-ablation: does retrieval sufficiency contribute anything?

This is the experiment that should have existed instead of the fuzzy-collapse
ablation (memo F4). Same pipeline, same data, same NLI calls, two conditions:

    (a) r pinned to 0.9     -- the constant r of the pre-Gate-B code (memo F1)
    (b) r computed by neutrorag.sufficiency

Both conditions use the CURRENT I = max(1-r, n). That is deliberate: the point
is to isolate r's contribution with the formula held fixed, not to confound it
with the Gate B change to I. A raw argmax(e, n, c) baseline is reported
alongside for reference -- it is the Gate A comparator and is unaffected by r.

The NLI model is not re-run: e/n/c are replayed from the committed
fever_run_200_current.csv, so all three systems see bit-identical model output
and the
only thing that varies is r.

    python experiments/run_r_ablation.py

Caveat that must be read with any result here (memo F9): FEVER supplies gold,
annotator-selected evidence with a constant relevance, and 185 of 200 rows carry
a single passage. Only the coverage component of r can vary; support_count is
near-constant and connectivity and diversity are unavailable. This ablation
therefore measures r under the conditions least favourable to it. It is not the
test of retrieval sufficiency -- that needs Step 9 data.
"""
from __future__ import annotations

import argparse
import csv
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "experiments"))

from make_results_table import (  # noqa: E402  -- reuse, do not duplicate metrics
    CHANNELS, accuracy, confusion, confusion_md, mcnemar_exact, per_class, wald_ci,
)
from neutrorag.fever import SUPPORT_TARGET, load_fever_hf  # noqa: E402
from neutrorag.scoring import NLIRetrievalScorer  # noqa: E402


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--csv", default="fever_run_200_current.csv")
    p.add_argument("--outdir", default="results")
    p.add_argument("--r-const", type=float, default=0.9)
    return p.parse_args()


class _ReplayNLI:
    """Replays one recorded (e, n, c) for every passage of a claim."""

    def __init__(self, triple, times):
        self._rows = [triple] * times
        self._i = 0

    def predict(self, premise, hypothesis):
        out = self._rows[self._i]
        self._i += 1
        return out


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                       cwd=REPO, text=True).strip()
    except Exception:  # pragma: no cover
        return "unknown"


def main() -> None:
    args = parse_args()
    rows = list(csv.DictReader(open(REPO / args.csv, encoding="utf-8")))
    examples = load_fever_hf(split="validation", max_examples=len(rows))

    gold, pred_const, pred_suff, pred_raw = [], [], [], []
    r_values = []

    for ex, row in zip(examples, rows):
        gold.append(ex.gold_channel)
        if row["e"] == "":
            # empty-evidence short circuit: no NLI output exists (memo F3)
            pred_const.append("I"); pred_suff.append("I"); pred_raw.append("I")
            continue
        e, n, c = float(row["e"]), float(row["n"]), float(row["c"])

        const = NLIRetrievalScorer(nli=_ReplayNLI((e, n, c), len(ex.evidence)),
                                   r_override=args.r_const,
                                   support_target=SUPPORT_TARGET)
        suff = NLIRetrievalScorer(nli=_ReplayNLI((e, n, c), len(ex.evidence)),
                                  support_target=SUPPORT_TARGET)
        pred_const.append(const.score(ex.claim, ex.evidence).dominant)
        pred_suff.append(suff.score(ex.claim, ex.evidence).dominant)
        pred_raw.append(max({"T": e, "I": n, "F": c}, key={"T": e, "I": n, "F": c}.get))
        r_values.append(suff.sufficiency(ex.claim, ex.evidence).r)

    systems = {
        f"(a) r = {args.r_const} constant": list(zip(gold, pred_const)),
        "(b) r = sufficiency": list(zip(gold, pred_suff)),
        "raw NLI argmax(e,n,c) [reference]": list(zip(gold, pred_raw)),
    }

    n = len(gold)
    commit = git_commit()
    lines = ["# The r-ablation: constant r vs. computed retrieval sufficiency", "",
             f"N = {n}, `copenlu/fever_gold_evidence` validation, NLI outputs replayed "
             f"from `{args.csv}` (model not re-run).", "",
             f"Generated by `python experiments/run_r_ablation.py` | commit `{commit}`", "",
             "Both r conditions use the current `I = max(1-r, n)`, so this isolates r "
             "with the formula held fixed.", "",
             "## r actually varied?", ""]

    r_sorted = sorted(r_values)
    lines += [f"- distinct values of r: **{len(set(round(v, 6) for v in r_values))}** "
              f"(pre-Gate-B this was 1)",
              f"- min {r_sorted[0]:.3f}, median {r_sorted[len(r_sorted) // 2]:.3f}, "
              f"max {r_sorted[-1]:.3f}",
              f"- rows with r <= 0.5 (the memo F12 regime where I >= 0.5 automatically): "
              f"**{sum(1 for v in r_values if v <= 0.5)}/{len(r_values)}**", ""]

    lines += ["## Headline", "", "| system | accuracy | 95% CI (Wald) | macro-F1 |",
              "|---|---:|---:|---:|"]
    stats = {}
    for name, pairs in systems.items():
        acc = accuracy(pairs)
        pc = per_class(confusion(pairs))
        macro = sum(v[2] for v in pc.values()) / len(CHANNELS)
        se, lo, hi = wald_ci(acc, n)
        stats[name] = (acc, macro, pc, confusion(pairs))
        lines.append(f"| {name} | {acc:.4f} | [{lo:.3f}, {hi:.3f}] | {macro:.4f} |")

    a_acc = stats[f"(a) r = {args.r_const} constant"][0]
    b_acc = stats["(b) r = sufficiency"][0]
    lines += ["", f"**(b) minus (a) = {b_acc - a_acc:+.4f} accuracy.**", ""]

    b_pairs = systems["(b) r = sufficiency"]
    a_pairs = systems[f"(a) r = {args.r_const} constant"]
    nb, nc, p = mcnemar_exact(b_pairs, a_pairs)
    differ = sum(1 for x, y in zip(a_pairs, b_pairs) if x[1] != y[1])
    lines += [f"Predictions differ on **{differ}/{n}** rows. Exact McNemar "
              f"(b = sufficiency only right = {nb}, c = constant only right = {nc}): "
              f"**p = {p:.4f}**.", ""]

    lines += ["## Per-class F1", "", "| class | (a) r const | (b) r sufficiency | raw NLI | support |",
              "|---|---:|---:|---:|---:|"]
    for ch in CHANNELS:
        pa = stats[f"(a) r = {args.r_const} constant"][2][ch]
        pb = stats["(b) r = sufficiency"][2][ch]
        pr = stats["raw NLI argmax(e,n,c) [reference]"][2][ch]
        lines.append(f"| {ch} | {pa[2]:.3f} | {pb[2]:.3f} | {pr[2]:.3f} | {pa[3]} |")
    lines.append("")

    lines.append("## Confusion matrices")
    lines.append("")
    for name, (_, _, _, conf) in stats.items():
        lines.append(confusion_md(conf, name))
        lines.append("")

    outdir = REPO / args.outdir
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "r_ablation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    with open(outdir / "r_ablation.csv", "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["system", "class", "precision", "recall", "f1", "support"])
        for name, (_, _, pc, _) in stats.items():
            for ch in CHANNELS:
                pr_, re_, f1_, sup = pc[ch]
                w.writerow([name, ch, f"{pr_:.4f}", f"{re_:.4f}", f"{f1_:.4f}", sup])
        w.writerow([])
        w.writerow(["system", "metric", "value"])
        for name, (acc, macro, _, _) in stats.items():
            w.writerow([name, "accuracy", f"{acc:.4f}"])
            w.writerow([name, "macro_f1", f"{macro:.4f}"])
        w.writerow(["paired(b_vs_a)", "mcnemar_b", nb])
        w.writerow(["paired(b_vs_a)", "mcnemar_c", nc])
        w.writerow(["paired(b_vs_a)", "mcnemar_exact_p", f"{p:.4f}"])
        w.writerow(["paired(b_vs_a)", "rows_differ", differ])

    print("\n".join(lines))
    print(f"wrote {outdir / 'r_ablation.md'} and {outdir / 'r_ablation.csv'}")


if __name__ == "__main__":
    main()
